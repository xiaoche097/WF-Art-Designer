#!/usr/bin/env node
const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");
const { pluginDir, registrationCode } = require("./uxp-registration.cjs");
const { buildLauncher, launcherEntries } = require("./windows-launcher.cjs");

const root = path.resolve(__dirname, "../..");
const dist = path.join(root, "dist");
const manifestPath = path.join(dist, "manifest.json");
const releaseRoot = path.resolve(root, "..", "WF美工助手公版");
const tempRoot = path.join(root, ".tmp-public-release");

const EXPECTED_PLUGIN_ID = "WfArtAssistant";
const EXPECTED_PANEL_ID = "wfArtAssistantPanel";
const variant = { suffix: "" };

function run(file, argsList, options = {}) {
    execFileSync(file, argsList, { cwd: options.cwd || root, stdio: "inherit" });
}

function writePackageInstallNotes({ zipDir, ccxDir }) {
    fs.writeFileSync(
        path.join(zipDir, "安装说明.txt"),
        "解压zip，复制WfArtAssistant文件夹到你本机的ps安装路径：Adobe Photoshop 2026\\Plug-ins。找不到可以右键桌面ps打开当前文件夹找到Plug-ins目录。右击一次没到ps目录就在当前打开的目录再找一次ps快捷方式继续右击。\n",
        "utf8"
    );
    fs.writeFileSync(
        path.join(ccxDir, "使用说明.txt"),
        "通过 Adobe Creative Cloud 打开 .ccx 安装包，然后在 Photoshop 的插件菜单中打开 WF美工助手。\n",
        "utf8"
    );
}

function psQuote(value) {
    return "'" + String(value).replace(/'/g, "''") + "'";
}

function walkFiles(dir, predicate, result = []) {
    if (!fs.existsSync(dir)) return result;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walkFiles(full, predicate, result);
        else if (entry.isFile() && (!predicate || predicate(full))) result.push(full);
    }
    return result;
}

function copyDistToStage(stageDir) {
    fs.rmSync(stageDir, { recursive: true, force: true });
    fs.mkdirSync(stageDir, { recursive: true });
    fs.cpSync(dist, stageDir, { recursive: true });

    // The webpack bundle already contains these host modules. Keeping the copied
    // source files in public packages only makes reverse engineering easier.
    fs.rmSync(path.join(stageDir, "host"), { recursive: true, force: true });
}

function writeInstallFileList(stageDir) {
    const listPath = path.join(stageDir, "wfa-installed-files.txt");
    fs.writeFileSync(listPath, "", "utf8");
    const files = walkFiles(stageDir).map((file) => path.relative(stageDir, file).replace(/\//g, "\\")).sort();
    fs.writeFileSync(listPath, files.join("\n") + "\n", "utf8");
}

function createZipFromDir(sourceDir, output) {
    const tempZip = output.endsWith(".zip") ? output : output + ".zip";
    fs.rmSync(output, { force: true });
    fs.rmSync(tempZip, { force: true });
    run("powershell.exe", [
        "-NoProfile",
        "-Command",
        "Compress-Archive -Path " + psQuote(path.join(sourceDir, "*")) + " -DestinationPath " + psQuote(tempZip) + " -Force",
    ]);
    if (tempZip !== output) fs.renameSync(tempZip, output);
}

function listZipEntries(archive) {
    const output = execFileSync("tar", ["-tf", archive], { encoding: "utf8" });
    return output.split(/\r?\n/).filter(Boolean);
}

function assertPackageShape(archive) {
    const entries = listZipEntries(archive);
    if (!entries.includes("manifest.json")) throw new Error(path.basename(archive) + " is missing manifest.json");
    if (entries.some((entry) => entry.startsWith("host/"))) {
        throw new Error(path.basename(archive) + " still contains copied host source files");
    }
}

function findInnoCompiler() {
    const candidates = [
        process.env.ISCC,
        path.join(process.env.LOCALAPPDATA || "", "Programs", "Inno Setup 6", "ISCC.exe"),
        "C:\\Program Files (x86)\\Inno Setup 6\\ISCC.exe",
        "C:\\Program Files\\Inno Setup 6\\ISCC.exe",
        "C:\\Program Files (x86)\\Inno Setup 5\\ISCC.exe",
        "C:\\Program Files\\Inno Setup 5\\ISCC.exe",
    ].filter(Boolean);
    for (const candidate of candidates) {
        if (fs.existsSync(candidate)) return candidate;
    }
    try {
        return execFileSync("where", ["ISCC.exe"], { encoding: "utf8" })
            .split(/\r?\n/)
            .map((line) => line.trim())
            .find(Boolean) || null;
    } catch {
        return null;
    }
}

function writeInnoScript({ stageDir, releaseDir, version, installerBaseName }) {
    const innoScript = path.join(releaseDir, installerBaseName + ".iss");
    const setupIcon = path.join(stageDir, "icons", "icon.ico");
    const lines = [
        "; Generated by scripts/release-installer/build-public-release.cjs",
        "#define MyAppName \"WF美工助手\"",
        "#define MyAppVersion \"" + version + "\"",
        "#define MySourceDir \"" + stageDir + "\"",
        "#define MyOutputDir \"" + releaseDir + "\"",
        "",
        "[Setup]",
        "AppId={{EBA62C92-A317-47C7-8E97-1F5BEBAE12A9}",
        "AppName={#MyAppName}",
        "AppVersion={#MyAppVersion}",
        "AppPublisher=WF美工助手",
        "DefaultDirName=" + pluginDir,
        "DisableDirPage=yes",
        "ArchitecturesAllowed=x64compatible",
        "ArchitecturesInstallIn64BitMode=x64compatible",
        "DisableProgramGroupPage=yes",
        "OutputDir={#MyOutputDir}",
        "OutputBaseFilename=" + installerBaseName,
        "Compression=lzma2",
        "SolidCompression=yes",
        "WizardStyle=modern",
        "PrivilegesRequired=admin",
        "Uninstallable=no",
        "UsePreviousAppDir=no",
        "DirExistsWarning=no",
        "CloseApplications=yes",
        "RestartApplications=no",
    ];
    if (fs.existsSync(setupIcon)) lines.push("SetupIconFile=" + setupIcon);
    lines.push(
        "",
        "[Languages]",
        "Name: \"chinesesimp\"; MessagesFile: \"compiler:Default.isl\"",
        "",
        "[Files]",
        "Source: \"{#MySourceDir}\\\\*\"; DestDir: \"{app}\"; Flags: ignoreversion recursesubdirs createallsubdirs",
        ...launcherEntries(releaseDir),
        "",
        "[Code]",
        ...registrationCode,
        "function IsSafePackagePath(RelPath: String): Boolean;",
        "begin",
        "  RelPath := Trim(RelPath);",
        "  Result := (RelPath <> '') and (Pos('..', RelPath) = 0) and (Pos(':', RelPath) = 0) and (Copy(RelPath, 1, 1) <> '\\') and (Copy(RelPath, 1, 1) <> '/');",
        "end;",
        "",
        "function GetPreserveRoot(): String;",
        "begin",
        "  Result := AddBackslash(ExpandConstant('{tmp}')) + 'wfa-preserve';",
        "end;",
        "",
        "function IsPreservedRelPath(RelPath: String): Boolean;",
        "begin",
        "  StringChangeEx(RelPath, '/', '\\', True);",
        "  Result := (RelPath = 'voices') or (Copy(RelPath, 1, 7) = 'voices\\') or (RelPath = 'forge_presets') or (Copy(RelPath, 1, 14) = 'forge_presets\\');",
        "end;",
        "",
        "procedure CopyTree(SourceDir: String; DestDir: String; FailIfExists: Boolean);",
        "var",
        "  FindRec: TFindRec;",
        "  SourcePath: String;",
        "  DestPath: String;",
        "begin",
        "  if not DirExists(SourceDir) then",
        "    Exit;",
        "  ForceDirectories(DestDir);",
        "  if FindFirst(AddBackslash(SourceDir) + '*', FindRec) then",
        "  begin",
        "    repeat",
        "      if (FindRec.Name <> '.') and (FindRec.Name <> '..') then",
        "      begin",
        "        SourcePath := AddBackslash(SourceDir) + FindRec.Name;",
        "        DestPath := AddBackslash(DestDir) + FindRec.Name;",
        "        if DirExists(SourcePath) then",
        "          CopyTree(SourcePath, DestPath, FailIfExists)",
        "        else",
        "          CopyFile(SourcePath, DestPath, FailIfExists);",
        "      end;",
        "    until not FindNext(FindRec);",
        "    FindClose(FindRec);",
        "  end;",
        "end;",
        "",
        "procedure PreserveFolder(FolderName: String);",
        "begin",
        "  CopyTree(AddBackslash(ExpandConstant('{app}')) + FolderName, AddBackslash(GetPreserveRoot()) + FolderName, False);",
        "end;",
        "",
        "procedure DeletePreservedPackageFile(RelPath: String);",
        "var",
        "  FullPath: String;",
        "begin",
        "  RelPath := Trim(RelPath);",
        "  if not IsSafePackagePath(RelPath) then",
        "    Exit;",
        "  StringChangeEx(RelPath, '/', '\\', True);",
        "  if not IsPreservedRelPath(RelPath) then",
        "    Exit;",
        "  FullPath := AddBackslash(GetPreserveRoot()) + RelPath;",
        "  if FileExists(FullPath) then",
        "    DeleteFile(FullPath);",
        "end;",
        "",
        "procedure RemoveKnownPackageFilesFromPreserve();",
        "var",
        "  Lines: TArrayOfString;",
        "  I: Integer;",
        "  ListPath: String;",
        "begin",
        "  ListPath := AddBackslash(ExpandConstant('{app}')) + 'wfa-installed-files.txt';",
        "  if LoadStringsFromFile(ListPath, Lines) then",
        "  begin",
        "    for I := 0 to GetArrayLength(Lines) - 1 do",
        "      DeletePreservedPackageFile(Lines[I]);",
        "  end;",
        "end;",
        "",
        "procedure PrepareCleanInstall();",
        "begin",
        "  DelTree(GetPreserveRoot(), True, True, True);",
        "  ForceDirectories(GetPreserveRoot());",
        "  PreserveFolder('voices');",
        "  PreserveFolder('forge_presets');",
        "  RemoveKnownPackageFilesFromPreserve();",
        "  if DirExists(ExpandConstant('{app}')) then",
        "    DelTree(ExpandConstant('{app}'), True, True, True);",
        "  ForceDirectories(ExpandConstant('{app}'));",
        "end;",
        "",
        "procedure RestorePreservedFolders();",
        "begin",
        "  CopyTree(GetPreserveRoot(), ExpandConstant('{app}'), True);",
        "  DelTree(GetPreserveRoot(), True, True, True);",
        "end;",
        "",
        "procedure CurStepChanged(CurStep: TSetupStep);",
        "begin",
        "  if CurStep = ssInstall then",
        "    PrepareCleanInstall();",
        "  if CurStep = ssPostInstall then",
        "  begin",
        "    RestorePreservedFolders();",
        "    RegisterWfArtAssistant;",
        "  end;",
        "end;",
        "",
        "[Messages]",
        "SetupAppTitle=WF美工助手"
    );
    fs.writeFileSync(innoScript, lines.join("\n") + "\n", "utf8");
    return innoScript;
}

function buildInstaller({ stageDir, releaseDir, version, installer }) {
    const installerBaseName = path.basename(installer, ".exe");
    const innoScript = writeInnoScript({ stageDir, releaseDir, version, installerBaseName });
    fs.rmSync(installer, { force: true });
    fs.rmSync(installer + ".sha256", { force: true });
    const iscc = findInnoCompiler();
    if (!iscc) {
        console.log("installer: skipped, Inno Setup ISCC.exe not found");
        fs.rmSync(innoScript, { force: true });
        return false;
    }
    buildLauncher(releaseDir, path.join(stageDir, "icons", "icon.ico"));
    run(iscc, [innoScript], { cwd: releaseDir });
    if (!fs.existsSync(installer)) throw new Error("Inno Setup did not create installer");
    fs.rmSync(innoScript, { force: true });
    return true;
}

function packageVariant(variant, version) {
    const suffix = variant.suffix ? "-" + variant.suffix : "";
    const folderName = version + suffix;
    const releaseDir = path.join(releaseRoot, folderName);
    const stageDir = path.join(tempRoot, folderName);
    const zipDir = path.join(releaseDir, "zip");
    const ccxDir = path.join(releaseDir, "ccx");
    const exeDir = path.join(releaseDir, "exe");
    const baseName = "WfArtAssistant-" + version + suffix;
    const zip = path.join(zipDir, baseName + ".zip");
    const ccx = path.join(ccxDir, baseName + ".ccx");
    const installer = path.join(exeDir, baseName + "-Installer.exe");

    copyDistToStage(stageDir);
    writeInstallFileList(stageDir);
    console.log("basic shield: removed copied host source; using production bundle without strong obfuscation");

    for (const dir of [zipDir, ccxDir, exeDir]) fs.mkdirSync(dir, { recursive: true });
    writePackageInstallNotes({ zipDir, ccxDir });
    for (const file of [zip, ccx, zip + ".sha256", ccx + ".sha256", installer, installer + ".sha256"]) {
        fs.rmSync(file, { force: true });
    }
    createZipFromDir(stageDir, zip);
    createZipFromDir(stageDir, ccx);
    assertPackageShape(zip);
    assertPackageShape(ccx);
    const hasInstaller = buildInstaller({ stageDir, releaseDir: exeDir, version, installer });

    console.log("release: " + releaseDir);
    console.log("zip: " + zip);
    console.log("ccx: " + ccx);
    console.log("installer: " + (hasInstaller ? installer : "not built"));
}

function main() {
    if (!fs.existsSync(manifestPath)) throw new Error("dist is missing manifest.json");
    const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
    const version = manifest.version;
    if (!version) throw new Error("manifest.json is missing version");
    if (manifest.id !== EXPECTED_PLUGIN_ID) {
        throw new Error(`manifest id must stay ${EXPECTED_PLUGIN_ID}; changing it creates a new UXP persistent folder`);
    }
    const panelIds = Array.isArray(manifest.entrypoints) ? manifest.entrypoints.map((entry) => entry?.id) : [];
    if (!panelIds.includes(EXPECTED_PANEL_ID)) {
        throw new Error(`manifest entrypoint id must include ${EXPECTED_PANEL_ID}; changing it can split UXP panel state`);
    }
    if (walkFiles(dist, (file) => file.endsWith(".map")).length) {
        throw new Error("release dist must not contain source maps");
    }
    fs.rmSync(tempRoot, { recursive: true, force: true });
    try {
        packageVariant(variant, version);
    } finally {
        fs.rmSync(tempRoot, { recursive: true, force: true });
    }
}

main();
